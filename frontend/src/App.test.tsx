import { act, render, screen, within } from "@testing-library/react"
import userEvent from "@testing-library/user-event"
import { describe, expect, it, vi } from "vitest"
import App from "./App"

describe("Switchboard landing interactions", () => {
  it("opens the labelled setup dialog, switches platforms, and closes with Escape", async () => {
    const user = userEvent.setup()
    render(<App />)
    const trigger = screen.getByRole("button", { name: "Run locally" })
    await user.click(trigger)
    const dialog = screen.getByRole("dialog", { name: "One connection to get started." })
    expect(within(dialog).getByRole("tabpanel")).toHaveTextContent("source .venv/bin/activate")
    expect(within(dialog).getByRole("tabpanel")).toHaveTextContent('@modelcontextprotocol/server-filesystem "$PWD"')
    expect(within(dialog).getByRole("tabpanel")).toHaveTextContent("switchboard serve --http 127.0.0.1:8765")
    expect(within(dialog).getByText("http://127.0.0.1:8765/mcp")).toBeInTheDocument()
    await user.click(within(dialog).getByRole("tab", { name: "Windows" }))
    expect(within(dialog).getByRole("tabpanel")).toHaveTextContent("Activate.ps1")
    expect(within(dialog).getByRole("tabpanel")).toHaveTextContent("npx.cmd -y @modelcontextprotocol/server-filesystem (Get-Location).Path")
    expect(within(dialog).getByRole("tabpanel")).toHaveTextContent("switchboard serve --http 127.0.0.1:8765")
    expect(within(dialog).getByRole("tabpanel")).not.toHaveTextContent("source .venv/bin/activate")
    await user.keyboard("{Escape}")
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument()
    expect(trigger).toHaveFocus()
  })

  it("reports copy success only after the clipboard write completes", async () => {
    const user = userEvent.setup()
    let finishCopy!: () => void
    const writeText = vi.fn(() => new Promise<void>(resolve => { finishCopy = resolve }))
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText } })
    render(<App />)
    await user.click(screen.getByRole("button", { name: "Run locally" }))
    await user.click(screen.getByRole("tab", { name: "Windows" }))
    await user.click(screen.getByRole("button", { name: "Copy commands" }))
    expect(writeText).toHaveBeenCalledWith(expect.stringContaining("Activate.ps1"))
    expect(screen.queryByRole("button", { name: "Copied" })).not.toBeInTheDocument()
    await act(async () => finishCopy())
    expect(screen.getByRole("button", { name: "Copied" })).toBeInTheDocument()
    expect(within(screen.getByRole("dialog")).getByRole("status")).toHaveTextContent("Commands copied to clipboard.")
    await user.click(screen.getByRole("tab", { name: "macOS / Linux" }))
    expect(screen.getByRole("button", { name: "Copy commands" })).toBeInTheDocument()
    expect(within(screen.getByRole("dialog")).getByRole("status")).toBeEmptyDOMElement()
  })

  it("offers manual copying when clipboard permission is denied", async () => {
    const user = userEvent.setup()
    const writeText = vi.fn().mockRejectedValue(new DOMException("Permission denied", "NotAllowedError"))
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText } })
    render(<App />)
    await user.click(screen.getByRole("button", { name: "Run locally" }))
    await user.click(screen.getByRole("button", { name: "Copy commands" }))
    expect(within(screen.getByRole("dialog")).getByRole("status")).toHaveTextContent("Clipboard unavailable. Select and copy the commands above.")
    expect(screen.queryByRole("button", { name: "Copied" })).not.toBeInTheDocument()
  })

  it("does not claim the new platform was copied when an earlier request finishes late", async () => {
    const user = userEvent.setup()
    let finishCopy!: () => void
    const writeText = vi.fn(() => new Promise<void>(resolve => { finishCopy = resolve }))
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { writeText } })
    render(<App />)
    await user.click(screen.getByRole("button", { name: "Run locally" }))
    await user.click(screen.getByRole("button", { name: "Copy commands" }))
    expect(writeText).toHaveBeenCalledWith(expect.stringContaining("source .venv/bin/activate"))
    await user.click(screen.getByRole("tab", { name: "Windows" }))
    await act(async () => finishCopy())
    expect(screen.getByRole("button", { name: "Copy commands" })).toBeInTheDocument()
    expect(within(screen.getByRole("dialog")).getByRole("status")).toBeEmptyDOMElement()
  })

  it("explains the workflow without displaying an executed plan", async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole("button", { name: "Explore the workflow" }))
    const dialog = screen.getByRole("dialog", { name: "Three steps. Two agent tools." })
    expect(within(dialog).getByText(/does not execute tools/)).toBeInTheDocument()
    const first = within(dialog).getByRole("button", { name: /index/ })
    const last = within(dialog).getByRole("button", { name: /run/ })
    expect(first).toHaveAttribute("aria-pressed", "true")
    await user.click(last)
    expect(last).toHaveAttribute("aria-pressed", "true")
    expect(first).toHaveAttribute("aria-pressed", "false")
    expect(within(dialog).getByRole("heading", { name: "Run the plan" })).toBeInTheDocument()
    expect(within(dialog).getByText("Results, or the step that failed")).toBeInTheDocument()
    await user.click(within(dialog).getByRole("button", { name: "Close" }))
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument()
    expect(screen.getByRole("button", { name: "Explore the workflow" })).toHaveFocus()
  })
  it("makes the illustrative source selector operable by keyboard", async () => {
    const user = userEvent.setup()
    render(<App />)
    const git = screen.getByRole("button", { name: "Git" })
    const filesystem = screen.getByRole("button", { name: "Filesystem" })
    expect(filesystem).toHaveAttribute("aria-pressed", "true")
    git.focus()
    await user.keyboard("{Enter}")
    expect(git).toHaveAttribute("aria-pressed", "true")
    expect(filesystem).toHaveAttribute("aria-pressed", "false")
  })

  it("traces the selected server and client without executing tools", async () => {
    const user = userEvent.setup()
    render(<App />)
    await user.click(screen.getByRole("button", { name: "Git" }))
    await user.click(screen.getByRole("button", { name: "Cursor" }))
    expect(screen.getByRole("button", { name: "Cursor" })).toHaveAttribute("aria-pressed", "true")
    expect(screen.getByRole("button", { name: "OpenCode" })).toHaveAttribute("aria-pressed", "false")
    expect(screen.getByRole("status")).toHaveTextContent("GitSwitchboardCursor")
    await user.click(screen.getByRole("button", { name: "Trace route" }))
    expect(screen.getByRole("status")).toHaveTextContent("TRACE 03")
    expect(screen.getByText(/An architectural illustration/)).toBeInTheDocument()
  })

  it("shows the gateway workflow without benchmark claims or sample data", () => {
    render(<App />)
    expect(screen.getByRole("link", { name: "Skip to content" })).toHaveAttribute("href", "#main")
    expect(screen.getByRole("link", { name: "Documentation" })).toHaveAttribute("href", "https://github.com/sakkshm/switchboard#install")
    expect(screen.getByRole("link", { name: "GitHub" })).toHaveAttribute("href", "https://github.com/sakkshm/switchboard")
    expect(screen.getByLabelText("Local gateway workflow")).toHaveTextContent("find")
    expect(screen.queryByRole("button", { name: "View the evidence" })).not.toBeInTheDocument()
    expect(document.body).not.toHaveTextContent(/3,444|acme\/api|schema tokens|synthetic/i)
  })
})
